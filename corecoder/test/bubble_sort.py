"""
冒泡排序（Bubble Sort）实现

功能说明：
    对输入的列表进行升序排序（从小到大）。
    冒泡排序是一种简单的排序算法，它重复地遍历待排序的列表，
    依次比较相邻两个元素，如果顺序错误就交换它们。

时间复杂度：
    - 最坏情况：O(n²) — 列表完全逆序
    - 最好情况：O(n) — 列表已经有序（使用优化标志）
    - 平均情况：O(n²)

空间复杂度：O(1) — 原地排序，只使用常数额外空间

稳定性：稳定排序（相等元素的相对位置不变）
"""


def bubble_sort(arr):
    """
    对列表进行冒泡排序（升序）

    参数：
        arr (list): 待排序的列表，元素应支持比较操作（如 int、float）

    返回值：
        list: 排序后的原列表（原地排序，返回引用本身）

    核心逻辑：
        1. 外层循环控制排序轮数，总共需要 n-1 轮
        2. 内层循环逐对比较相邻元素
        3. 如果前一个元素大于后一个元素，则交换它们
        4. 优化：如果某一轮没有发生任何交换，说明列表已经有序，提前结束
    """
    n = len(arr)
    # 外层循环：共进行 n-1 轮遍历
    for i in range(n - 1):
        # 标志位：记录本轮是否发生过交换
        swapped = False

        # 内层循环：比较相邻元素
        # 每轮结束后，最大的元素会"冒泡"到末尾，因此范围可以递减
        for j in range(n - 1 - i):
            # 如果前一个元素大于后一个元素，则交换
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swapped = True  # 标记发生了交换

        # 优化：如果本轮没有交换，说明列表已有序，提前退出
        if not swapped:
            break

    return arr


if __name__ == "__main__":
    # ----- 使用示例 -----
    # 定义待排序的列表
    sample_list = [64, 34, 25, 12, 22, 11, 90]

    print("排序前：", sample_list)

    # 调用冒泡排序函数（原地排序）
    sorted_list = bubble_sort(sample_list)

    print("排序后：", sorted_list)
